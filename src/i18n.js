function code() {
  const value = String(preferences.get("language") || "fr-FR");
  return STRINGS[value] ? value : "fr-FR";
}

function bundle(lang) {
  return STRINGS[lang || code()] || STRINGS["fr-FR"];
}

function t(key, vars) {
  let text = bundle()[key] || STRINGS["en-US"][key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (name) {
      text = text.replace(`{${name}}`, vars[name]);
    });
  }
  return text;
}

